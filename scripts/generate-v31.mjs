import fs from 'node:fs';
import assert from 'node:assert/strict';
const source=JSON.parse(fs.readFileSync(new URL('../data/cardpool-v31.json',import.meta.url),'utf8'));
const cards=source.cards;
assert.equal(new Set(cards.map(c=>c.id)).size,cards.length);
for(const c of cards){
 assert([4,8].includes(c.hours));assert.equal(c.copies,4);
 assert(c.price>=0&&Number.isInteger(c.price));
 for(const r of 'WABC')assert([...c.requires].filter(x=>x===r).length<=cards.filter(x=>x.route===r&&x.kind==='growth').length);
 if(c.kind==='growth'){assert([2,3].includes(c.progress));assert(c.cost.money>0);assert(c.minSanity>0);}
 if(c.maturation)assert(c.kind==='repeat'&&!c.progress);
}
const row=c=>[c.id+' '+c.name,c.hours+'h',c.price+(c.requires?' / '+c.requires:''),c.support-c.stress,
 [c.capital?'锁本金'+c.capital:'',c.parallel?'白天并行':'',c.professional?'工作白天免查岗':'',c.offHours?'仅非上班时间':''].filter(Boolean).join('；')||'—',
 [c.minSanity?'理智≥'+c.minSanity:'',c.inspirationRequired?'灵感≥'+c.inspirationRequired:'',c.cost.money||c.upkeep?'资金−'+((c.cost.money||0)+c.upkeep):'',c.gain.profit?'收入+'+c.gain.profit:'',c.gain.cash?'奖金+'+c.gain.cash:'',c.condition==='lowSanity'?'理智≤2另加奖金1':'',c.dice?'骰面收益 '+c.dice.faces.join('/'):'',c.inspirationGenerate?'空夜灵感+'+c.inspirationGenerate:'',c.opportunity?(c.inspirationSpend?'可消耗灵感1，看3免费取1':'看3原价买1'):'',c.handDiscardBonus?'可弃手牌1，收入另+'+c.handDiscardBonus:'',c.maturation?'前2次收入'+c.maturation.initial+'，之后'+c.maturation.mature:'',c.hireFee?(c.hireDrawCount?'4h暗堆看3招聘1':'明牌/手牌招聘1'):'',c.permission==='weekend'?'完成后下周起永久双休、基础理智+2':'',c.permission==='protection'?'完成后下周起每周保护一张4h':''].filter(Boolean).join('；')||'—',
 c.progress?c.progress+'次完成'+(c.kind==='growth'?'归档'+c.route:''):c.maturation?'重复 / 2枚成熟进度':'重复'];
const outputs={
 'src/cardpool-data.js':'// Generated by npm run generate from data/cardpool-v31.json.\nexport default '+JSON.stringify(source,null,2)+';\n',
 'docs/cards-v0.31.md':'# v0.31 卡池\n\n'+cards.length+'种，每种固定4张，共'+cards.length*4+'张。4h市场8张，8h市场4张。工资与奖金不计逃离；其他收入计入。全池替换旧卡。数值为待实测模型，不是平衡结论。\n\n| 卡牌 | 时间 | 买价 / 技能 | 日程理智 | 打出限制 | 执行 | 持久度 |\n|---|---|---|---|---|---|---|\n'+cards.map(c=>'| '+row(c).join(' | ')+' |').join('\n')+'\n'
};
for(const [name,text]of Object.entries(outputs)){
 const target=new URL('../'+name,import.meta.url);
 if(process.argv.includes('--check'))assert.equal(fs.readFileSync(target,'utf8').replaceAll('\r\n','\n'),text,name+' stale');
 else fs.writeFileSync(target,text);
}
console.log(`v0.31: ${cards.length} card types, ${cards.length*4} physical cards; ${process.argv.includes('--check')?'verified':'generated'}.`);
