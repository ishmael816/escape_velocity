import fs from 'node:fs';
import assert from 'node:assert/strict';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import {markerRules} from '../src/marker-rules.js';
import { validatePool } from '../src/card-studio-model.js';
export function generateOutputs(source){
const errors=validatePool(source);
if(errors.length)throw Error(errors.join('\n'));
const cards=source.cards;
assert.equal(new Set(cards.map(c=>c.id)).size,cards.length);
for(const c of cards){
 assert([4,8].includes(c.hours));assert.equal(c.copies,4);
 assert(c.price>=0&&Number.isInteger(c.price));
 for(const r of 'WABC')assert([...c.requires].filter(x=>x===r).length<=cards.filter(x=>x.route===r&&x.kind==='growth').length);
 if(source.rulesVersion===31&&c.kind==='growth'){assert([2,3].includes(c.progress));assert(c.cost.money>0);assert(c.minSanity>0);}
 if(c.maturation)assert(c.kind==='repeat'&&!c.progress);
}
const row=c=>[c.id+' '+c.name,c.hours+'h',c.price+(c.requires?' / '+c.requires:''),(c.support||0)-(c.stress||0),
 [c.capital?'锁本金'+c.capital:'',c.parallel?'白天并行':'',c.professional?'工作白天免查岗':'',c.mechanic?.playSpend?'打出消耗 '+c.mechanic.playSpend+' 1':'',c.offHours?'仅非上班时间':''].filter(Boolean).join('；')||'—',
 [markerRules(c),c.minSanity?'理智≥'+c.minSanity:'',c.maxSanity<10?'理智≤'+c.maxSanity:'',c.inspirationRequired?'灵感≥'+c.inspirationRequired:'',c.cost.money||c.upkeep?'资金−'+((c.cost.money||0)+(c.upkeep||0)):'',c.gain.profit?'收入+'+c.gain.profit:'',c.gain.cash?'奖金+'+c.gain.cash:'',c.condition==='lowSanity'?'理智≤'+c.lowSanityAt+'另加奖金'+c.conditionalBonus:'',c.dice?'骰面'+(c.dice.resource==='profit'?'副业':'资金')+' '+c.dice.faces.join('/'):'',c.inspirationGenerate?'空夜灵感+'+c.inspirationGenerate:'',c.opportunity?(c.inspirationSpend?'可消耗灵感1，':'')+'看'+c.opportunity.count+(c.opportunity.free?'免费取1':'原价买1'):'',c.handDiscardBonus?'可弃手牌1，收入另+'+c.handDiscardBonus:'',c.maturation?'前'+c.maturation.steps+'次收入'+c.maturation.initial+'，之后'+c.maturation.mature:'',c.hireFee&&!c.mechanic?.hire?(c.hireDrawCount?'4h暗堆看'+c.hireDrawCount+'招聘1':'明牌/手牌招聘1'):'',c.permission==='weekend'?'完成后下周起永久双休、基础理智+2':'',c.permission==='protection'?'完成后下周起每周保护一张4h':''].filter(Boolean).join('；')||'—',
 c.progress?c.progress+'次完成'+(c.kind==='growth'?'归档'+c.route:''):c.maturation?'重复 / '+c.maturation.steps+'枚成熟进度':c.kind==='once'?'一次性（执行后弃置）':'重复'];
const outputs={
 'src/cardpool-data.js':'// Generated by npm run generate from data/cardpool-v31.json.\nexport default '+JSON.stringify(source,null,2)+';\n',
 ['docs/cards-v0.'+source.rulesVersion+'.md']:'# v0.'+source.rulesVersion+' 卡池\n\n'+cards.length+'种，每种固定4张，共'+cards.length*4+'张。I级按四流派分列，每列2张；II级混合为一个公共牌堆，展示4张。周一全员首次行动无人购买后，依次各刷新一行I级或一张II级；刷新后保护至下周，仍可购买。工资、奖金、交易所得不计逃离；仅标注副业的收入计入。全池替换旧卡。数值为待实测模型，不是平衡结论。\n\n| 卡牌 | 时间 | 买价 / 技能 | 日程理智 | 打出限制 | 执行 | 持久度 |\n|---|---|---|---|---|---|---|\n'+cards.map(c=>'| '+row(c).join(' | ')+' |').join('\n')+'\n'
};
return outputs;
}
if(process.argv[1]&&path.resolve(process.argv[1])===fileURLToPath(import.meta.url)){
const source=JSON.parse(fs.readFileSync(new URL('../data/cardpool-v31.json',import.meta.url),'utf8'));
for(const [name,text]of Object.entries(generateOutputs(source))){
 const target=new URL('../'+name,import.meta.url);
 if(process.argv.includes('--check'))assert.equal(fs.readFileSync(target,'utf8').replaceAll('\r\n','\n'),text,name+' stale');
 else fs.writeFileSync(target,text);
}
console.log(`v0.${source.rulesVersion}: ${source.cards.length} card types, ${source.cards.length*4} physical cards; ${process.argv.includes('--check')?'verified':'generated'}.`);
}
